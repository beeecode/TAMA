export const STATUS_LABELS: Record<TaskStatus, string> = {
  backlog: "Backlog",
  todo: "To do",
  in_progress: "In progress",
  review: "In review",
  blocked: "Blocked",
  done: "Done",
};

/** Column order for the board, left to right. */
export const BOARD_COLUMNS: TaskStatus[] = [
  "todo",
  "in_progress",
  "review",
  "blocked",
  "done",
];

const byId = new Map<ID, Task>(tasks.map((task) => [task.id, task]));

export function getTask(id: ID | null | undefined): Task | undefined {
  if (!id) return undefined;
  return byId.get(id);
}

export function tasksByStatus(status: TaskStatus, list: Task[] = tasks): Task[] {
  return list.filter((task) => task.status === status);
}

export function tasksForProject(projectId: ID, list: Task[] = tasks): Task[] {
  return list.filter((task) => task.projectId === projectId);
}

export function tasksForPerson(personId: ID, list: Task[] = tasks): Task[] {
  return list.filter((task) => task.assigneeId === personId);
}

export function openTasks(list: Task[] = tasks): Task[] {
  return list.filter((task) => task.status !== "done");
}

/** Open work sorted by how much it deserves attention today. */
export function tasksByRisk(list: Task[] = tasks): Task[] {
  return openTasks(list).sort((a, b) => taskRiskScore(b) - taskRiskScore(a));
}

export function blockingTasks(task: Task): Task[] {
  return task.blockedByIds
    .map((id) => byId.get(id))
    .filter((t): t is Task => Boolean(t));
}
